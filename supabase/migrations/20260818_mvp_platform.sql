drop policy if exists orders_insert on public.orders;
create policy orders_insert
on public.orders for insert
with check (user_id is null or auth.uid() = user_id);

drop policy if exists orders_admin_update on public.orders;
create policy orders_admin_update
on public.orders for update
using (public.is_admin())
with check (public.is_admin());

drop policy if exists order_items_read on public.order_items;
create policy order_items_read
on public.order_items for select
using (
  exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
      and ((auth.uid() is not null and o.user_id = auth.uid()) or public.is_admin())
  )
);

drop policy if exists order_items_insert on public.order_items;
create policy order_items_insert
on public.order_items for insert
with check (
  exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
      and (o.user_id is null or o.user_id = auth.uid() or public.is_admin())
  )
);

drop policy if exists order_history_read on public.order_status_history;
create policy order_history_read
on public.order_status_history for select
using (
  exists (
    select 1 from public.orders o
    where o.id = order_status_history.order_id
      and ((auth.uid() is not null and o.user_id = auth.uid()) or public.is_admin())
  )
);

drop policy if exists inventory_public_read on public.inventory;
create policy inventory_public_read
on public.inventory for select
using (true);

drop policy if exists inventory_admin_all on public.inventory;
create policy inventory_admin_all
on public.inventory for all
using (public.is_admin())
with check (public.is_admin());

commit;
